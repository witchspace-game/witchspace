// Bundles what the MCP server reads (the fleet, the design documents, AGENTS.md,
// CONTRIBUTING.md and the ship schema) for the Worker, which can't read files,
// and compiles the ship schema check ahead of time, since Workers can't compile
// code at run time. Run before deploying the Worker (wrangler's build step
// in server/wrangler.toml does it), and by the local server (tools/mcp.ts) directly.
//
//   npx tsx tools/mcp-data.ts     writes server/src/mcp-data.json and server/src/mcp-schema.js

import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import type { ShipDef } from '../src/content/types';
import { loadDocs } from './docs';

const root = resolve(import.meta.dirname, '..');

export function loadMcpData() {
  const shipDir = join(root, 'content/ships');
  const ships: ShipDef[] = readdirSync(shipDir)
    .filter((f) => f.endsWith('.json'))
    .map((f) => {
      const { $schema: _, ...ship } = JSON.parse(readFileSync(join(shipDir, f), 'utf8'));
      return ship as ShipDef;
    })
    .sort((a, b) => a.name.localeCompare(b.name));
  const docs = loadDocs(root);
  const texts = {
    agents: readFileSync(join(root, 'AGENTS.md'), 'utf8'),
    contributing: readFileSync(join(root, 'CONTRIBUTING.md'), 'utf8'),
    schema: readFileSync(join(root, 'schemas/ship.schema.json'), 'utf8'),
  };
  return { ships, docs, texts };
}

/** Ajv's error list, as plain sentences an assistant can act on. */
export function describeErrors(errors: { instancePath?: string; message?: string; params?: Record<string, unknown> }[] | null | undefined): string[] {
  return (errors ?? []).map((e) => {
    const where = e.instancePath || '(the ship)';
    const extra = e.params?.additionalProperty ? ` ("${e.params.additionalProperty}")` : e.params?.allowedValues ? ` (one of: ${(e.params.allowedValues as string[]).join(', ')})` : '';
    return `${where} ${e.message ?? 'is invalid'}${extra}`;
  });
}

/** The schema check, compiled now: for the local server. */
export function compileSchemaCheck(schema: string) {
  const ajv = new Ajv2020({ allErrors: true });
  const check = ajv.compile(JSON.parse(schema));
  return (ship: unknown) => (check(ship) ? [] : describeErrors(check.errors));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = loadMcpData();
  writeFileSync(join(root, 'server/src/mcp-data.json'), JSON.stringify(data));
  const ajv = new Ajv2020({ allErrors: true, code: { source: true, esm: true } });
  const validate = ajv.compile(JSON.parse(data.texts.schema));
  // Ajv's runtime helpers come in as CommonJS requires; the one the ship schema uses is inlined, so the module is plain ESM.
  const code = standaloneCode(ajv, validate).replace(
    'require("ajv/dist/runtime/ucs2length").default',
    '((s) => { let n = 0; for (const _ of s) n++; return n; })',
  );
  if (code.includes('require(')) throw new Error('The compiled schema check needs another Ajv runtime helper: inline it here.');
  writeFileSync(join(root, 'server/src/mcp-schema.js'), `// Generated by tools/mcp-data.ts from schemas/ship.schema.json. Don't edit.\n${code}`);
  console.log(`MCP data: ${data.ships.length} ships, ${data.docs.length} documents.`);
}
